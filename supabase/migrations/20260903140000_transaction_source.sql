-- 거래가 어디서 왔는지
--
-- 앱이 장부의 주인이 되면서 거래를 앱에서 **쓰고 고칠 수 있어야** 하는데,
-- 무엇을 고쳐도 되는지가 **출처에 달렸다.**
--
--   statement — 거래내역서에서 불러온 것. 금액·날짜·통장은 **통장의 기록**이다.
--               고치면 통장과 어긋나 대조가 뜻을 잃는다. 적요·분류·분할만 고친다.
--   manual    — 사람이 손으로 넣은 것. 전부 사람이 적은 값이라 다 고칠 수 있다.
--               농협은 인터넷뱅킹이 없어 거래내역 파일이 안 나오므로 **늘 이쪽**이다.
--
-- 통장 이름('농협'/'모임')으로 유추할 수도 있다. 지금은 그 유추가 100% 맞는다 —
-- 모임은 토스에서 불러오고 농협은 손으로 넣으니까. 그런데 손으로 넣은 모임 거래가
-- **한 건이라도** 생기면 바로 어긋나고, 어긋난 걸 알아챌 방법이 없다.
-- 유추가 맞는 지금 적어 두는 게 나중에 되살리는 것보다 싸다.
--
-- 기존 273건은 수기 장부 이관분이라 전부 manual 이다 (기본값 그대로 맞다).
alter table public.finance_transactions
    add column source text not null default 'manual'
        check (source in ('manual', 'statement'));

comment on column public.finance_transactions.source is
    'manual = 사람이 앱에서 넣음 (금액·날짜·통장 편집 가능) / statement = 거래내역서에서 불러옴 (통장 기록이라 잠금)';
