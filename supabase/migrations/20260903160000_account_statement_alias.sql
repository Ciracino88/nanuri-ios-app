-- 통장이 상대 내역서에 찍히는 이름
--
-- 농협과 모임 사이의 이체는 **반드시 모임통장을 지나므로 토스 거래내역서에 찍힌다.**
-- 예산 수령은 `ATM입금 … 예수교대한성결고천교`, 월말 잔액 반환은 `출금 …
-- 예수교대한성결고천교` 다. 토스는 상대 예금주 이름을 적요에 넣기 때문이다.
--
-- 그래서 **적요가 농협 통장의 예금주 이름이면 그 줄은 내부 이체다.** 그 이름을
-- 앱이 알아야 판정할 수 있는데, `finance_accounts` 는 `name`('농협'·'모임')만
-- 갖고 있었다. 그건 사람이 부르는 이름이지 은행이 찍는 이름이 아니다.
--
-- 이 한 칸이 양방향을 다 덮는다 — 들어오는 쪽도 나가는 쪽도 같은 이름이 찍힌다.
--
-- 안 하면 그 줄이 평범한 입금으로 들어가고, **농협 잔액이 400만원 많고 총 재정과
-- 총 입금이 그만큼 부풀며 월말 0원 검산이 성립하지 않는다.** 보고서에는 원래
-- 안 나오므로(filteredExternal) 출력물만 봐서는 안 드러난다.
--
-- 모임통장은 비워 둔다. 농협 내역서가 없어서(인터넷뱅킹 없음) 이 이름이 쓰일
-- 자리가 없다. 나중에 통장이 늘면 그때 채운다.
alter table public.finance_accounts
    add column statement_alias text;

comment on column public.finance_accounts.statement_alias is
    '이 통장이 상대 통장 거래내역서의 적요에 찍히는 이름(예금주). 내부 이체 판정에 쓴다.';

update public.finance_accounts
   set statement_alias = '예수교대한성결고천교'
 where name = '농협';
