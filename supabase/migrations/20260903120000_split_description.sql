-- 분할 조각에 적요를 준다
--
-- 분할 조각은 `memo` 라는 자유 입력 칸을 처음부터 갖고 있었다. 그런데 그 값은
-- **어디에도 안 나왔다** — 보고서 상세 명세의 적요 칸은 카테고리를 쓰고,
-- 카테고리가 비면 **부모 거래의** 적요로 떨어졌다. 편집 시트 안에서만 보이는
-- 값이었다.
--
-- 그래서 한 출금을 다섯 조각으로 쪼개면 보고서에 다섯 줄이 나오되 이름은
-- 카테고리뿐이고, "누구에게 나간 돈인가" 는 다섯 줄이 부모 거래의 적요 하나를
-- 나눠 가졌다. 묶어 보내기로 여러 청구를 한 번에 처리하는 이 앱에서 그 다섯 줄은
-- 서로 다른 사람에게 간 돈이다.
--
-- 칸을 새로 만들지 않고 그 `memo` 를 적요로 승격시킨다. 거래(`finance_transactions`)
-- 가 `description`(적요)과 `memo`(메모)를 따로 갖는 건 **출처가 둘이기 때문이다** —
-- 앞은 은행이 준 값이고 뒤는 사람이 적는 값이다. 분할 조각은 전부 사람이 적는
-- 값이라 그 구분이 없다. 칸을 늘리면 자유 입력 칸이 둘이 되고, 같은 말을 어디에
-- 적을지가 매번 흔들린다.
--
-- 이름을 `description` 으로 맞춰 **두 표에서 적요가 같은 이름을 갖게 한다.**
--
-- ⚠️ 이 이름은 앱과 짝이다 (ARCHITECTURE.md "반드시 같이 고쳐야 하는 짝").
--    이 마이그레이션만 적용하고 앱을 안 올리면 분할 저장이 통째로 실패한다.
alter table public.finance_splits rename column memo to description;
